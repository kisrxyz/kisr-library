/**
 * Синтетическая книга для E2E: шапка, короткое вступление, пять глав по ~600 слов, «Что делать» с двумя
 * задачами, колода из 8 карточек и «Источники». Текст — заглушки, но каждый абзац свой: ключ блока
 * (`hash` собственного текста) тогда у каждого абзаца свой, и тест видит разницу между соседними блоками.
 * Генератор детерминирован (одно и то же зерно — один и тот же текст). Настоящие книги владельца сюда не попадают.
 */

export interface FixtureChapter {
  /** Название главы, как оно на экране. */
  title: string;
  /** Слово, которое есть только в этой главе (для поиска); у служебных глав — `null`. */
  rare: string | null;
}

export interface FixtureBook {
  md: string;
  title: string;
  category: string;
  tags: string[];
  /** Главы так, как их видит читатель: `chapters[0]` — глава 1. Вступление короче 40 слов и приклеено к главе 1. */
  chapters: FixtureChapter[];
}

