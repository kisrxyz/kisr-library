const CHAPTERS: FixtureChapter[] = [
  { title: 'Первая ступень', rare: 'астролябия' },
  { title: 'Вторая ступень', rare: 'горизонталь' },
  { title: 'Третья ступень', rare: 'перламутровый' },
  { title: 'Четвёртая ступень', rare: 'полынья' },
  { title: 'Пятая ступень', rare: 'метроном' },
];

export function makeBook(opts: { title?: string; seed?: number } = {}): FixtureBook {
  const title = opts.title ?? 'Книга про дорогу и привалы';
  const seed = opts.seed ?? 7;
  used.clear();

  const category = 'Проверка';
  const tags = ['дорога', 'привалы', 'синтетика'];
  const parts: string[] = [
    '---',
    `title: ${title}`,
    `category: ${category}`,
    `tags: [${tags.join(', ')}]`,
    'summary: Синтетическая книга для автотестов: пять глав, задачи, карточки и источники.',
    '---',
    // Меньше 40 слов: парсер приклеит вступление к первой главе, и номера глав на экране совпадут с порядком `CHAPTERS`
    'Это учебная книга-заглушка для проверки приложения. Факты в ней условные, а текст нужен только затем, чтобы у каждого абзаца был свой ключ.',
    '',
  ];

  CHAPTERS.forEach((chapter, i) => {
    parts.push(`## ${chapter.title}`, '');
    parts.push(prose(seed * 100 + i, 600, chapter.rare).join('\n\n'), '');
  });

  parts.push(
    '## Что делать',
    '',
    prose(seed * 100 + 90, 60, null).join('\n\n'),
    '',
    '- [ ] Собрать рюкзак по списку',
    '- [ ] Записать, где был самый долгий привал',
    '',
    '## Карточки',
    '',
    '```cards',
    CARDS.map(([q, a]) => `Q: ${q}\nA: ${a}`).join('\n\n'),
    '```',
    '',
    '## Источники',
    '',
    '- [Автор, 2020. Условный справочник путника](https://example.com/trail)',
    '',
  );

  const chapters: FixtureChapter[] = [
    ...CHAPTERS,
    { title: 'Что делать', rare: null },
    { title: 'Карточки', rare: null },
    { title: 'Источники', rare: null },
  ];
  return { md: parts.join('\n'), title, category, tags, chapters };
}
