const CONNECTORS = [', потому что', ', и поэтому', ', хотя', ', а значит', ', когда', '; при этом'];

/** Предсказуемый генератор псевдослучайных чисел (mulberry32). */
function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const wordCount = (s: string): number => (s.match(/[\p{L}\p{N}]+/gu) ?? []).length;
const capital = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);

/** Предложения не повторяются во всей книге: абзац с тем же текстом имел бы тот же ключ блока. */
const used = new Set<string>();

function sentence(next: () => number): string {
  for (;;) {
    const a = Math.floor(next() * CLAUSES.length);
    const b = Math.floor(next() * CLAUSES.length);
    if (a === b) continue;
    const connector = CONNECTORS[Math.floor(next() * CONNECTORS.length)];
    const text = `${capital(CLAUSES[a])}${connector} ${CLAUSES[b]}.`;
    if (used.has(text)) continue;
    used.add(text);
    return text;
  }
}

/** Абзацы по 4–6 предложений, пока не наберётся `words` слов. `rare` вставляется в один из средних абзацев. */
function prose(seed: number, words: number, rare: string | null): string[] {
  const next = rng(seed);
  const paragraphs: string[] = [];
  let total = 0;
  while (total < words) {
    const count = 4 + Math.floor(next() * 3);
    const sentences = Array.from({ length: count }, () => sentence(next));
    const text = sentences.join(' ');
    paragraphs.push(text);
    total += wordCount(text);
  }
  if (rare) {
    const at = Math.floor(paragraphs.length / 2);
    paragraphs[at] += ` Именно здесь встречается слово «${rare}», которого нет ни в одной другой главе.`;
  }
  return paragraphs;
}

